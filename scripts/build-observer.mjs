// The MAIN and ISOLATED registrations must not share a script URL. In regular
// Chrome the shared parser was skipped in MAIN at document_start, losing the
// initial native response. Use one self-contained entry point for MAIN.
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=new URL('../',import.meta.url);
export async function buildObserver(){
  const files=['lib/page-data.js','lib/render-data.js','lib/direct-api.js','capture.js'];
  const parts=await Promise.all(files.map(file=>readFile(new URL(`extension/${file}`,root),'utf8')));
  const bundle='// Generated by scripts/build-observer.mjs; edit its source files.\n'+parts.map((source,i)=>`// ${files[i]}\n${source}`).join('\n;\n')+'\n';
  const target=new URL('extension/observer.js',root);
  if(await readFile(target,'utf8').catch(()=>null)!==bundle)await writeFile(target,bundle);
}
if(process.argv[1]&&fileURLToPath(import.meta.url)===process.argv[1])await buildObserver();
